#!/usr/bin/env python3
"""Write the review document of the hizb split round from its splits.tsv.

    python scripts/review_hizb.py [reviews/2026-10-18-hizb-splits]

For every juz it shows each candidate start for its second hizb, with its balance, the text
around it, the decision and the reason. It also shows the 11 juz-start splits with both new
topics. Re-run it after editing the decisions to keep the document in step.
"""

import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from tajzee import juz as J  # noqa: E402
from tajzee import quran, reviews, rub, scores  # noqa: E402


def main() -> None:
    folder = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "reviews" / "2026-10-18-hizb-splits"
    rows = list(csv.DictReader(open(folder / "splits.tsv", encoding="utf-8"), delimiter="\t"))
    q = quran.load()
    ur = rub.ayat(reviews.reading())   # before the round
    un = rub.ayat()                    # now
    c = rub.mix(ur)
    js = scores.traditional_starts(8) + [len(ur)]
    before = rub.solve(ur).starts
    after = rub.solve(un).starts
    idx = {(u.sura, u.aya): u.index for u in ur}

    def dev_fn(j):
        a, b = js[j], js[j + 1]
        tot = sum(c[a:b])
        pre = J._prefix(c[a:b])
        return lambda i: (pre[i - a] - tot / 2) / (tot / 2) * 100

    by_juz = {}
    for r in rows:
        if r["reason"] == "hizb":
            by_juz.setdefault(int(r["juz"]), []).append(r)
    juz_rows = [r for r in rows if r["reason"] == "juz"]
    calls = [r for r in rows if r["reason"] == "hizb" and ("بديل" in r["note"])]

    o = []
    w = o.append
    w("# Review round 2026-10-18: hizb splits\n")
    w("*Generated by `scripts/review_hizb.py` from `splits.tsv`. Edit the decisions there, not here.*\n")
    w("## What was done\n")
    w("The juz are the traditional 30. Each juz is cut into two hizb, and every boundary must open a "
      "subject phrase (Task 1). The second hizb of each juz was checked on its own:\n\n"
      "1. **Balance.** For every aya end inside the juz, compute how even the two hizb would be if the "
      "second hizb started there. The number shown is the first hizb against half the juz, on the "
      "50/50 mix of recitation and print length: −1.5% means the first hizb is 1.5% short and the "
      "second 1.5% long.\n"
      "2. **Candidates.** The aya ends closer to balance than the start the solver had before this round "
      "(the best phrase start of the original reading). All of them fell inside a phrase.\n"
      "3. **Reading.** Each candidate was read in context. It is accepted only at a complete stop "
      "(*waqf tāmm*): the aya before it closes its sentence and its subject, and the aya after it does "
      "not lean on it. A reply (قال، قالوا), a pronoun or a demonstrative pointing back (أولئك، الذين), "
      "a «ف»/«ثم» continuation, a description of what came before, or the refrain of Ar-Raḥmān "
      "belongs with what precedes it.\n"
      "4. **Choice.** Where several candidates qualify, the one closest to balance is accepted. Where none "
      "qualifies, the earlier start is kept, even if less even.\n"
      "5. **Juz starts.** The 11 traditional juz starts that fall inside a phrase split that phrase, because "
      "each is also a hizb start.\n\n"
      "An accepted split becomes a phrase boundary with a topic for each half. The solver then picks the "
      "best phrase start, which is the accepted candidate.\n")

    w("## How to change a decision\n")
    w("1. In `splits.tsv`, set `decision` to `accept` or `reject` on the row of that candidate. Leave the "
      "other rows as they are.\n"
      "2. For a row you accept, fill in `topic_first` and `topic_second`: the topics of the phrase before "
      "and after the new start. If you leave them empty, both halves keep the old topic.\n"
      "3. Rebuild and re-solve:\n\n"
      "```sh\npython scripts/apply_splits.py            # shows what will change\n"
      "python scripts/apply_splits.py --write\nmake scores juz rub paper\n"
      "python scripts/review_hizb.py             # refresh this document\n```\n\n"
      "If you accept more than one candidate in the same juz, all become phrase starts and the solver "
      "takes the most even. To force a particular one, accept only that one. To prefer a start "
      "that is not listed (e.g. a surah opening that is already a phrase start), reject every "
      "candidate of that juz that is closer to balance than it.\n")

    w("## Summary\n")
    sm = []
    for j in range(30):
        dev = dev_fn(j)
        b0, a0 = before[8 * j + 4], after[8 * j + 4]
        rs = by_juz.get(j + 1, [])
        acc = [r for r in rs if r["decision"] == "accept"]
        if not rs:
            d = "already the best point"
        elif acc:
            d = "**split** at " + ", ".join(r["new_start"] for r in acc)
        else:
            d = f"kept: {len(rs)} candidate{'s' if len(rs) > 1 else ''} rejected"
        sm.append([j + 1, f"{ur[b0].ref} ({dev(b0):+.1f}%)", f"{un[a0].ref} ({dev(a0):+.1f}%)", d])
    w("| juz | second hizb before | now | decision |\n|---|---|---|---|")
    w("\n".join("| " + " | ".join(map(str, r)) + " |" for r in sm) + "\n")

    w("\n## Judgment calls\n")
    w("The rejected candidates below are not clear-cut: they could open a hizb and were turned down for a "
      "stronger or more even alternative. These are the ones most worth a second look.\n\n")
    w("| juz | candidate | balance | note |\n|---|---|---|---|")
    w("\n".join(f"| {r['juz']} | {r['new_start']} | {r['hizb_dev_pct']}% | {r['note']} |" for r in calls) + "\n")

    w("\n## Juz by juz\n")
    w("In the text: ¶ marks a phrase start of the original reading, with its topic. ▶ is the "
      "second-hizb start before this round, ★ an accepted new start, ✗ a rejected candidate. The "
      "percentage after each aya is the balance if the second hizb started at that aya.\n")
    for j in range(30):
        rs = by_juz.get(j + 1)
        if not rs:
            continue
        dev = dev_fn(j)
        b0, a0 = before[8 * j + 4], after[8 * j + 4]
        cand = {idx[tuple(map(int, r["new_start"].split(":")))]: r for r in rs}
        lo, hi = min(list(cand) + [b0]), max(list(cand) + [b0])
        while lo > js[j] and not ur[lo].phrase_start:  # back to the start of the phrase
            lo -= 1
        w(f"\n### Juz {j + 1}: second hizb {ur[b0].ref} ({dev(b0):+.1f}%) → {un[a0].ref} ({dev(a0):+.1f}%)\n")
        lines = []
        for i in range(lo, hi + 1):
            u = ur[i]
            if u.phrase_start:
                lines.append(f"¶ *{u.topic}*")
            mark = "▶" if i == b0 else ("★" if cand.get(i, {}).get("decision") == "accept"
                                        else ("✗" if i in cand else "·"))
            lines.append(f"{mark} **{u.ref}** ({dev(i):+.1f}%) {q.ayat[i].text}")
        w("\n" + "  \n".join(lines) + "\n")
        w("\n| candidate | balance | decision | reason |\n|---|---|---|---|")
        w("\n".join(f"| {r['new_start']} | {r['hizb_dev_pct']}% | {'**accept**' if r['decision'] == 'accept' else 'reject'} "
                    f"| {r['note']} |" for r in rs) + "\n")
        for r in rs:
            if r["decision"] == "accept":
                w(f"\nNew phrases: {r['sura']}:{r['from']}–{r['split_after']} *{r['topic_first']}* · "
                  f"{r['new_start']}–{r['to']} *{r['topic_second']}*\n")

    w("\n## Juz starts that split a phrase\n")
    w("These follow the traditional juz, which are kept; only the topics are open to change.\n")
    for r in juz_rows:
        s, sa = int(r["sura"]), int(r["split_after"])
        w(f"\n### Juz {r['juz']} starts at {s}:{sa + 1}\n")
        lines = []
        for a in range(int(r["from"]), int(r["to"]) + 1):
            i = idx[(s, a)]
            if a == sa + 1:
                lines.append(f"¶ *{r['topic_second']}*")
            elif a == int(r["from"]):
                lines.append(f"¶ *{r['topic_first']}*")
            lines.append(f"{'★' if a == sa + 1 else '·'} **{s}:{a}** {q.ayat[i].text}")
        w("\n" + "  \n".join(lines) + "\n")

    out = folder / "README.md"
    out.write_text("\n".join(o))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
