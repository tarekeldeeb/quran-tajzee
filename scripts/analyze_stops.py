#!/usr/bin/env python3
"""Grade every hizb and rubʿ boundary by the classical works on pauses, and compare
al-Ṣafāqusī's quarter ends with the Madina Mushaf.

Writes docs/research/stop-grades-analysis.md and data/rub/boundary-grades.tsv.
Uses only committed data (data/source/waqf/, built by scripts/extract_waqf.py).
"""

import collections
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from tajzee import DATA, quran, rub, scores, waqf  # noqa: E402

CLASSES = waqf.CLASSES
grade_of = waqf.boundary


def table(rows, header):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def summary(us, starts):
    inner = [i for i in starts if i]
    c = collections.Counter(grade_of(us, i)[0] for i in inner)
    return c, len(inner)


def main() -> None:
    q = quran.load()
    us = rub.ayat()
    new = rub.solve(us).starts
    trad = scores.traditional_starts(1)
    juz = set(trad[::8])
    S = waqf.stops()
    qs = waqf.quarters()

    # agreement of the two books where both grade an aya end
    both = [(waqf.RANK[v["muktafa"]], waqf.RANK[v["manar"]]) for v in S.values() if len(v) == 2]
    same = sum(a == b for a, b in both)
    near = sum(abs(a - b) <= 1 for a, b in both)
    n_mk = sum("muktafa" in v for v in S.values())
    n_mn = sum("manar" in v for v in S.values())

    ct, nt = summary(us, trad)
    cm, nm = summary(us, rub.solve(us, objective="minimax+lsq").starts)
    mix_strong = (cm["surah end"] + cm["تام"] + cm["كاف"]) / nm * 100
    cn, nn = summary(us, new)
    strong = lambda c: c["surah end"] + c["تام"] + c["كاف"]  # noqa: E731

    o = []
    w = o.append
    w("# The boundaries graded by the classical works on pauses\n")
    w("*Generated by `scripts/analyze_stops.py`. Data: `data/source/waqf/`, built from the OpenITI texts by "
      "`scripts/extract_waqf.py`.*\n")
    w("The phrase test that places every new boundary is this project's own reading. This report checks "
      "it against three classical judges:\n\n"
      "- **al-Dānī** (d. 444 AH), *al-Muktafā fī al-Waqf wa-l-Ibtidāʾ*;\n"
      "- **al-Ushmūnī** (d. c. 1100 AH), *Manār al-Hudā fī Bayān al-Waqf wa-l-Ibtidāʾ*;\n"
      "- **al-Ṣafāqusī** (d. 1118 AH), *Ghayth al-Nafʿ*, whose note on the last word of every quarter gives "
      "its grade, how widely it is accepted, and the alternatives of the Maghāriba and the Mashāriqa.\n\n"
      "The grades, strongest first: **تام** (complete: the next aya is independent in wording and meaning), "
      "**كاف** (sufficient: independent in wording, linked in meaning), **حسن** (good: a stop, but the next "
      "words depend on these), **جائز/صالح** (permissible), **ليس بوقف** (not a stop). A boundary is graded "
      "by the aya end before it, with the stronger grade where the two books differ. The end of a surah "
      "is a complete stop by convention («آخر السورة تام») and is counted on its own.\n")

    w("## 1. The extraction\n")
    w(f"- al-Muktafā grades **{n_mk:,}** aya ends, Manār al-Hudā **{n_mn:,}**; both grade {len(both):,}.\n"
      f"- Where both grade an aya end they give the same grade {same / len(both) * 100:.0f}% of the time, "
      f"and grades at most one step apart {near / len(both) * 100:.0f}% of the time. Two independent books, "
      "parsed independently, would not agree this well if the quotes were placed on the wrong ayat.\n"
      f"- Ghayth al-Nafʿ: the quarter-end note was located for **{sum(1 for x in qs if x.ghayth_end)}** of "
      f"240 quarters.\n"
      "- Quotes are matched to ayat by their consonant skeleton, so the imlāʾī spelling of the books "
      "matches the Uthmani text. Manār numbers its quotes; al-Muktafā's are placed in order inside their "
      "surah. The edition's typo «نام» for «تام» is read as «تام» (e.g. 25:20).\n")

    w("## 2. The boundaries graded\n")
    w(f"The {nt} inner boundaries of each division (hizb and quarter starts; the 30 juz starts are shared):\n")
    rows = [[k, ct[k], f"{ct[k] / nt * 100:.0f}%", cn[k], f"{cn[k] / nn * 100:.0f}%"] for k in CLASSES]
    rows.append(["**surah end, تام or كاف**", f"**{strong(ct)}**", f"**{strong(ct) / nt * 100:.0f}%**",
                 f"**{strong(cn)}**", f"**{strong(cn) / nn * 100:.0f}%**"])
    w(table(rows, ["grade of the aya end before it", "traditional", "", "new", ""]))
    w(f"\nBoth divisions end almost every quarter at a complete or sufficient stop: {strong(cn) / nn * 100:.0f}% of "
      f"the new boundaries against {strong(ct) / nt * 100:.0f}% of the traditional ones; the new division has "
      "more تام stops and fewer surah ends. The quarters are solved with pause points taken from these "
      "grades, so for them this is not an independent check. Solved on size alone (the 50/50 mix, "
      f"`objective=\"minimax+lsq\"`), the quarters already reach {mix_strong:.0f}%: the phrase test by itself "
      "places the boundaries as well as the classical stops do.\n")

    weak = []
    for i in new:
        if not i:
            continue
        cl, mk, mn = grade_of(us, i)
        if cl in ("حسن", "جائز/صالح", "ليس بوقف", "not graded"):
            weak.append((i, cl, mk, mn))
    w("\n### New boundaries the books grade below كاف\n")
    w("These are the cases where the classical grade is weaker than the phrase test assumed. Each is "
      "worth a second reading: the next aya leans on this one.\n")
    rows = []
    for i, cl, mk, mn in weak:
        e = us[i - 1]
        rows.append([us[i].ref, "traditional too" if i in set(trad) else "new", cl, mk or "–", mn or "–",
                     "… " + " ".join(quran.plain(q.ayat[i - 1].text).split()[-4:]),
                     " ".join(quran.plain(q.ayat[i].text).split()[:4]) + " …"])
    w(table(rows, ["start", "", "grade", "al-Muktafā", "Manār", "end of the aya before", "start"]))

    tw = [(i, *grade_of(us, i)) for i in trad if i and grade_of(us, i)[0] in ("حسن", "جائز/صالح", "ليس بوقف")]
    w(f"\nThe traditional boundaries graded below كاف: " + ", ".join(
        f"{us[i].ref} ({cl})" for i, cl, _, _ in tw) + ".\n")

    w("\n### The traditional juz that open inside a dialogue\n")
    w("The phrase test puts these juz starts inside a passage. The books grade the aya end before them:\n")
    rows = []
    for r in ("18:75", "51:31", "37:145"):
        i = next(u.index for u in us if u.ref == r)
        cl, mk, mn = grade_of(us, i)
        rows.append([r, "juz start" if i in juz else "hizb/quarter", cl, mk or "–", mn or "–"])
    w(table(rows, ["start", "", "grade", "al-Muktafā", "Manār"]))
    w("\nSo a passage the phrase test keeps whole can still contain a sufficient stop. The phrase test is "
      "stricter than the classical grade: it asks that the next aya open a new subject, not only a new "
      "sentence.\n")

    w("## 3. al-Ṣafāqusī's quarters and the Madina Mushaf\n")
    loc = [x for x in qs if x.ghayth_end]
    agree = [x for x in loc if x.ghayth_end == x.madina_end]
    st = collections.Counter(x.standing for x in loc)
    gr = collections.Counter(x.grade for x in loc)
    w(f"Of the {len(loc)} quarter ends located, **{len(agree)}** are the Madina end. Ghayth grades the last word "
      f"تام {gr['تام']} times and كاف {gr['كاف']} times, and states how widely the end is accepted:\n")
    w(table([["consensus (بإجماع، اتفاقا، بلا خلاف)", st["consensus"]],
             ["well known or his choice (المشهور، الجمهور، عليه عملنا)", st["well-known"]],
             ["one region (المغاربة or المشارقة)", st["regional"]],
             ["some (عند بعض، جماعة)", st["some"]],
             ["not stated", st["stated"]]], ["standing", "quarters"]))
    diff = [x for x in loc if x.ghayth_end != x.madina_end]
    named = [x for x in diff if waqf.madina_named(x)]
    w(f"\nThe {len(diff)} quarters where his end is not the Madina one. In {len(named)} of them he reports the "
      "Madina end as an alternative («… قبله»، «… بعده»، «عند المشارقة»); in the other "
      f"{len(diff) - len(named)} the Madina Mushaf departs from him:\n")
    w(table([[x.n, x.madina_end, x.ghayth_end, "yes" if waqf.madina_named(x) else "**no**", x.standing,
              x.note[:160]] for x in diff],
            ["quarter", "Madina ends", "Ghayth ends", "Madina end named", "standing", "his note"]))
    miss = [x for x in qs if not x.ghayth_end]
    w(f"\nNot located ({len(miss)}): quarters " + ", ".join(str(x.n) for x in miss) +
      ", where the note does not use the usual wording.\n")

    w("\n## 4. New boundaries on traditional positions\n")
    mad = {x.madina_end for x in qs}
    gha = {x.ghayth_end for x in loc}
    on_m = sum(1 for i in new if i and us[i - 1].ref in mad)
    on_g = sum(1 for i in new if i and us[i - 1].ref in gha and us[i - 1].ref not in mad)
    w(f"{on_m} of the new boundaries fall on a Madina quarter end and {on_g} more on an end that only "
      "al-Ṣafāqusī gives. The rest are new positions, chosen for balance among the complete stops.\n")

    out = ROOT / "docs" / "research" / "stop-grades-analysis.md"
    out.write_text("\n".join(o))
    with open(DATA / "rub" / "boundary-grades.tsv", "w", encoding="utf-8", newline="") as fh:
        wr = csv.writer(fh, delimiter="\t", lineterminator="\n")
        wr.writerow(["division", "start", "grade", "muktafa", "manar"])
        for name, starts in (("traditional", trad), ("new", new)):
            for i in starts:
                if i:
                    wr.writerow([name, us[i].ref, *grade_of(us, i)])
    print(f"wrote {out}")
    print("traditional", dict(ct), "\nnew", dict(cn))


if __name__ == "__main__":
    main()
