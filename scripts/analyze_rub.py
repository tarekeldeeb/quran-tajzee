#!/usr/bin/env python3
"""Analysis of the Task 4 hizb and rub' against the traditional ones.

Writes docs/tasks/04-hizb-rub-analysis.md and data/rub/analysis.json. Uses only committed
data (per-aya scores, phrases, traditional rub' starts).
"""

import json
import statistics as st
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from tajzee import DATA, rub, scores  # noqa: E402

INF = float("inf")
W = 0.5


def stats(xs):
    return dict(cv=st.pstdev(xs), worst=max(abs(x) for x in xs), min=min(xs), max=max(xs),
                ratio=(1 + max(xs)) / (1 + min(xs)))


def measure(us, starts):
    """hizb against 1/2 juz, rub' against 1/4 hizb, per score."""
    vals = dict(recitation=[u.recitation for u in us], typesetting=[u.typeset_px for u in us],
                combined=rub.mix(us, W))
    return {name: dict(hizb=stats(rub.relative(us, starts[::4], v, 2)), rub=stats(rub.relative(us, starts, v, 4)))
            for name, v in vals.items()}


def table(rows, header):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def pct(x, sign=False):
    return f"{x * 100:+.1f}%" if sign else f"{x * 100:.1f}%"


def main() -> None:
    us = rub.ayat()
    trad = scores.traditional_starts(1)
    d = rub.solve(us)
    R = dict(traditional=measure(us, trad), new=measure(us, d.starts))
    c = rub.mix(us, W)

    # methods and settings
    pz = dict(objective="penalized")
    variants = [
        ("**default**: nested, phrase starts only, minimax + least squares", d),
        ("joint (8 rubʿ per juz at once), phrase starts only", rub.solve(us, method="joint")),
        ("nested, phrase starts only, least squares", rub.solve(us, mid_phrase=INF, cap=None, **pz)),
        ("penalized: mid-phrase rubʿ at m 15%", rub.solve(us, mid_phrase=0.15, cap=None, **pz)),
        ("penalized: m 10%, cap ±10%", rub.solve(us, **pz)),
        ("penalized: m 5%", rub.solve(us, mid_phrase=0.05, cap=None, **pz)),
        ("any aya end, hizb too (m 0)", rub.solve(us, mid_phrase=0.0, hizb_mid_phrase=0.0, cap=None, **pz)),
    ]
    vrows, vmeta = [], []
    for name, x in variants:
        m = measure(us, x.starts)["combined"]
        hz_inside = sum(1 for s in x.hizb_starts() if s in set(x.mid_phrase))
        vrows.append([name, f"±{pct(m['hizb']['worst'])}", pct(m["hizb"]["cv"]), f"±{pct(m['rub']['worst'])}",
                      pct(m["rub"]["cv"]), len(x.mid_phrase), hz_inside])
        vmeta.append(dict(name=name, hizb_worst=m["hizb"]["worst"], rub_worst=m["rub"]["worst"],
                          inside=len(x.mid_phrase)))

    rel = rub.relative(us, d.starts, c, 4)
    trel = rub.relative(us, trad, c, 4)
    hrel = rub.relative(us, d.hizb_starts(), c, 2)
    threl = rub.relative(us, trad[::4], c, 2)
    same = len(set(d.starts) & set(trad))
    hsame = len(set(d.hizb_starts()) & set(trad[::4]))
    shifts = [abs(a - b) for a, b in zip(d.starts, trad)]
    juz_inside = [us[j].ref for j in d.juz_starts if not us[j].phrase_start]
    jset = set(d.juz_starts)
    tr_inside = sum(1 for i in trad if not us[i].phrase_start and i not in jset)

    def worst(vals, starts, unit, k=6):
        idx = sorted(range(len(vals)), key=lambda i: -abs(vals[i]))[:k]
        b = list(starts) + [len(us)]
        return [[i + 1, i // unit + 1, f"{us[b[i]].ref}–{us[b[i + 1] - 1].ref}", pct(vals[i], True)] for i in idx]

    meta = dict(traditional=R["traditional"], new=R["new"], variants=vmeta, same_rub_starts=same,
                same_hizb_starts=hsame, median_shift_ayat=st.median(shifts), juz_start_inside_phrase=juz_inside,
                rub_inside_phrase=len(d.mid_phrase), traditional_inside_phrase=tr_inside)
    (DATA / "rub" / "analysis.json").write_text(json.dumps(meta, ensure_ascii=False, indent=1) + "\n")

    t, n = R["traditional"]["combined"], R["new"]["combined"]
    o = []
    w = o.append
    w("# Task 4 — Hizb and rubʿ: analysis\n")
    w("Generated by `scripts/analyze_rub.py`; do not edit by hand. Method: "
      "[04-hizb-rub.md](04-hizb-rub.md). The juz are the traditional 30 (Madina Mushaf). Inside each "
      "juz the two hizb are cut first, then each hizb into four rubʿ. Each hizb is measured against "
      "1/2 of its juz and each rubʿ against 1/4 of its hizb, the targets the solver works to.\n")

    w("## 1. Balance: new against traditional\n")
    rows = []
    for level in ("hizb", "rub"):
        for name in ("recitation", "typesetting", "combined"):
            a, b = R["traditional"][name][level], R["new"][name][level]
            rows.append([{"rub": "rubʿ (of ¼ hizb)", "hizb": "hizb (of ½ juz)"}[level], name, pct(a["cv"]),
                         pct(b["cv"]), f"{pct(a['min'], True)} / {pct(a['max'], True)}",
                         f"{pct(b['min'], True)} / {pct(b['max'], True)}", f"{a['ratio']:.2f}×",
                         f"{b['ratio']:.2f}×"])
    w(table(rows, ["level", "score", "CV trad.", "CV new", "range trad.", "range new",
                   "longest/shortest trad.", "new"]))
    w(f"\nThe hizb go from ±{t['hizb']['worst'] * 100:.0f}% to ±{n['hizb']['worst'] * 100:.1f}% of half "
      f"their juz, and the rubʿ from ±{t['rub']['worst'] * 100:.0f}% to ±{n['rub']['worst'] * 100:.1f}% of a "
      "quarter of their hizb. Recitation and print move together, so balancing the mix balances "
      "each of them.\n")

    w("## 2. Methods and settings\n")
    w("The default starts every hizb and rubʿ at a phrase start, and minimises the worst unit, then "
      "the sum of squares. The penalized rows let a rubʿ start inside a phrase, at a penalty m: such a "
      "start costs as much as a rubʿ m off its target. The cap is a hard limit on every rubʿ. In all "
      "rows but the last, a hizb must start at a phrase start.\n")
    w(table(vrows, ["variant", "worst hizb", "hizb CV", "worst rubʿ", "rubʿ CV", "rubʿ inside a phrase",
                    "of which hizb"]))
    w(f"\nThe hizb are the same in every nested row. Their worst case, ±{n['hizb']['worst'] * 100:.1f}%, "
      "is set by phrase granularity in one juz. For the rubʿ, phrase granularity is the limit: a hizb "
      "holds about 18 phrases, 4.6 per rubʿ, and one long phrase can be a fifth of a rubʿ. Each phrase "
      "split accepted in review (section 6) moves the default towards the penalized rows without ever "
      "cutting a phrase.\n")

    w("## 3. Agreement with the traditional starts\n")
    w(f"- {hsame} of the 60 new hizb starts are traditional ones; 30 of them are the fixed juz starts.\n"
      f"- {same} of the 240 rubʿ starts are traditional ones.\n"
      f"- A new rubʿ start is typically {st.median(shifts):g} ayat from the traditional start of the same "
      "rubʿ (median).\n"
      f"- {len(d.mid_phrase)} new rubʿ starts fall inside a phrase. Traditionally {tr_inside} of the "
      "210 inner starts do.\n")

    w("## 4. Worst cases\n")
    w("Hizb, traditional (against 1/2 of their juz):\n\n")
    w(table(worst(threl, trad[::4], 2), ["hizb", "juz", "ayat", "combined"]))
    w("\nHizb, new:\n\n")
    w(table(worst(hrel, d.hizb_starts(), 2), ["hizb", "juz", "ayat", "combined"]))
    w("\nRubʿ, traditional (against 1/4 of their hizb):\n\n")
    w(table(worst(trel, trad, 8), ["rubʿ", "juz", "ayat", "combined"]))
    w("\nRubʿ, new:\n\n")
    w(table(worst(rel, d.starts, 8), ["rubʿ", "juz", "ayat", "combined"]))

    # how often each traditional level starts inside a phrase, and how deep
    pstart = {}
    for x in us:
        if x.phrase_start:
            cur = x.index
        pstart[x.index] = cur
    plen = {}
    for i, x in enumerate(us):
        plen[pstart[i]] = plen.get(pstart[i], 0) + 1
    cuts_rows, levels = [], {"juz": [], "hizb": [], "rub": []}
    for k, i in enumerate(trad):
        level = "juz" if k % 8 == 0 else ("hizb" if k % 4 == 0 else "rub")
        if not us[i].phrase_start:
            into, length = i - pstart[i], plen[pstart[i]]
            levels[level].append(into / length)
            first = us[pstart[i]]
            cuts_rows.append([k + 1, level, us[i].ref, f"{first.ref}–{us[pstart[i] + length - 1].ref}", into,
                              length, first.topic])
    with open(DATA / "rub" / "traditional-phrase-cuts.tsv", "w", encoding="utf-8") as fh:
        fh.write("rub\tlevel\tstart\tphrase\tayat_into_phrase\tphrase_ayat\ttopic\n")
        for r in cuts_rows:
            fh.write("\t".join(map(str, r)) + "\n")
    newcuts = sum(1 for k, i in enumerate(d.starts) if not us[i].phrase_start and k % 8)
    meta["traditional_phrase_cuts"] = {k: len(v) for k, v in levels.items()}
    meta["new_phrase_cuts"] = newcuts
    (DATA / "rub" / "analysis.json").write_text(json.dumps(meta, ensure_ascii=False, indent=1) + "\n")

    w("\n## 5. Boundaries that cut into a phrase\n")
    w("A boundary cuts into a phrase when it starts a unit in the middle of a Task 1 subject phrase. The "
      "next aya then continues the subject of the last aya of the previous unit. Each unit is "
      "counted at its own level: a juz start is also a hizb and rubʿ start, but it is counted once, "
      "as a juz.\n")
    total = {"juz": 30, "hizb": 30, "rub": 180}
    label = {"juz": "juz starts", "hizb": "second-hizb starts", "rub": "other rubʿ starts"}
    rows = []
    for k in ("juz", "hizb", "rub"):
        v = levels[k]
        rows.append([label[k], f"{len(v)} of {total[k]} ({len(v) / total[k] * 100:.0f}%)",
                     f"{st.median(v) * 100:.0f}%" if v else "–", "0" if k != "juz" else "kept (traditional)"])
    allv = sum(levels.values(), [])
    rows.append(["all 240", f"{len(allv)} of 240 ({len(allv) / 240 * 100:.0f}%)", f"{st.median(allv) * 100:.0f}%",
                 f"{newcuts} beyond the {len(levels['juz'])} juz"])
    w(table(rows, ["boundary", "traditional: inside a phrase", "median depth into the phrase", "new"]))
    w(f"\nThe traditional hizb and rubʿ cut into a phrase {len(levels['hizb']) + len(levels['rub'])} times "
      f"out of 210. **The new hizb and rubʿ never do:** every one of them opens a phrase. The only phrases "
      f"cut are by the {len(levels['juz'])} traditional juz starts that are kept as they are. Splitting those "
      "phrases in review (next section) removes even those. Depth is how far into the phrase the boundary "
      "falls, as a share of the phrase's ayat. Every case is listed in "
      "`data/rub/traditional-phrase-cuts.tsv`.\n")

    hint = rub.solve(us, objective="penalized")
    w("\n## 6. Phrases to review\n")
    w(f"`data/rub/phrase-splits.tsv` lists {len(juz_inside) + len(hint.mid_phrase)} proposed phrase splits:\n\n"
      f"- {len(juz_inside)} with reason `juz`, where a traditional juz start falls inside a phrase: "
      f"{', '.join(juz_inside)}. Since the juz are kept, these splits are needed for every boundary to open "
      "a phrase.\n"
      f"- {len(hint.mid_phrase)} with reason `balance`. Here the penalized objective would start a rubʿ "
      "inside a phrase. Splitting that phrase gives the solver that start while keeping the rule that "
      "every boundary opens a phrase.\n\n"
      "Re-run `make rub` after applying a review round.\n")
    out = ROOT / "docs" / "tasks" / "04-hizb-rub-analysis.md"
    out.write_text("\n".join(o))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
