#!/usr/bin/env python3
"""Analysis of the Task 4 hizb and rub' against the traditional ones.

Writes docs/tasks/04-hizb-rub-analysis.md and data/rub/analysis.json. Uses only committed
data (per-aya scores, phrases, traditional rub' starts).
"""

import json
import statistics as st
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from tajzee import DATA, rub, scores  # noqa: E402

INF = float("inf")
W = 0.5


def stats(xs):
    return dict(cv=st.pstdev(xs), worst=max(abs(x) for x in xs), min=min(xs), max=max(xs),
                ratio=(1 + max(xs)) / (1 + min(xs)))


def measure(us, starts):
    vals = dict(recitation=[u.recitation for u in us], typesetting=[u.typeset_px for u in us],
                combined=rub.mix(us, W))
    hz = starts[::4]
    return {name: dict(rub=stats(rub.relative(us, starts, v, 8)), hizb=stats(rub.relative(us, hz, v, 2)))
            for name, v in vals.items()}


def table(rows, header):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def pct(x, sign=False):
    return f"{x * 100:+.1f}%" if sign else f"{x * 100:.1f}%"


def main() -> None:
    us = rub.ayat()
    trad = scores.traditional_starts(1)
    d = rub.solve(us)
    R = dict(traditional=measure(us, trad), new=measure(us, d.starts))

    # sweep of the mid-phrase penalty, no cap, so the pure trade-off shows
    sweep = []
    for m in (0.0, 0.05, 0.08, 0.10, 0.15, 0.20, INF):
        x = rub.solve(us, W, m, INF, None)
        mm = measure(us, x.starts)["combined"]
        sweep.append(dict(m=m, rub_cv=mm["rub"]["cv"], rub_worst=mm["rub"]["worst"],
                          hizb_worst=mm["hizb"]["worst"], inside=len(x.mid_phrase)))
    free = rub.solve(us, W, 0.0, 0.0, None)  # every aya end allowed, also for hizb
    free_m = measure(us, free.starts)["combined"]

    mixv = rub.relative(us, d.starts, rub.mix(us, W), 8)
    tmix = rub.relative(us, trad, rub.mix(us, W), 8)
    same = sorted(set(d.starts) & set(trad))
    shifts = [abs(a - b) for a, b in zip(d.starts, trad)]
    juz_inside = [us[j].ref for j in d.juz_starts if not us[j].phrase_start]
    tr_inside = sum(1 for i in trad if not us[i].phrase_start and i not in set(d.juz_starts))

    def worst(vals, starts, k=6):
        idx = sorted(range(len(vals)), key=lambda i: -abs(vals[i]))[:k]
        b = list(starts) + [len(us)]
        return [[i + 1, i // 8 + 1, f"{us[b[i]].ref}–{us[b[i + 1] - 1].ref}", pct(vals[i], True)] for i in idx]

    meta = dict(traditional=R["traditional"], new=R["new"], sweep=sweep, same_starts=len(same),
                median_shift_ayat=st.median(shifts), juz_start_inside_phrase=juz_inside,
                rub_inside_phrase=len(d.mid_phrase), traditional_inside_phrase=tr_inside)
    (DATA / "rub" / "analysis.json").write_text(json.dumps(meta, ensure_ascii=False, indent=1, default=str) + "\n")

    o = []
    w = o.append
    w("# Task 4 — Hizb and rubʿ: analysis\n")
    w("Generated by `scripts/analyze_rub.py`; do not edit by hand. Method: "
      "[04-hizb-rub.md](04-hizb-rub.md). The juz are the traditional 30 (Madina Mushaf); only the "
      "hizb and rubʿ inside each juz are new. Every rubʿ is measured against 1/8 of its own juz and "
      "every hizb against 1/2, so the juz-to-juz differences (±6%, Task 3) are not counted here.\n")

    w("## 1. Balance: new against traditional\n")
    rows = []
    for level in ("rub", "hizb"):
        for name in ("recitation", "typesetting", "combined"):
            t, n = R["traditional"][name][level], R["new"][name][level]
            rows.append([{"rub": "rubʿ", "hizb": "hizb"}[level], name, pct(t["cv"]), pct(n["cv"]),
                         f"{pct(t['min'], True)} / {pct(t['max'], True)}",
                         f"{pct(n['min'], True)} / {pct(n['max'], True)}",
                         f"{t['ratio']:.2f}×", f"{n['ratio']:.2f}×"])
    w(table(rows, ["level", "score", "CV trad.", "CV new", "range trad.", "range new",
                   "longest/shortest trad.", "new"]))
    t, n = R["traditional"]["combined"], R["new"]["combined"]
    w(f"\nRelative to its share of the juz, the longest traditional rubʿ is {t['rub']['ratio']:.1f}× the shortest; the new "
      f"rubʿ stay within ±{n['rub']['worst'] * 100:.0f}% of their target ({n['rub']['ratio']:.2f}×). "
      f"Hizb go from ±{t['hizb']['worst'] * 100:.0f}% to ±{n['hizb']['worst'] * 100:.1f}%. The two scores "
      "move together, so balancing the mix balances each.\n")

    w("## 2. Where a rubʿ may start\n")
    w("Every hizb starts at a phrase start (a new subject). A rubʿ may also start at another aya end "
      "inside a phrase, as the traditional rubʿ do, at a penalty m: such a start costs as much as a rubʿ "
      "m off its target. Without a cap:\n")
    rows = [["∞ (phrase starts only)" if s["m"] == INF else pct(s["m"]), pct(s["rub_cv"]),
             f"±{pct(s['rub_worst'])}", f"±{pct(s['hizb_worst'])}", s["inside"]] for s in sweep]
    rows.append(["0, hizb too (any aya end)", pct(free_m["rub"]["cv"]), f"±{pct(free_m['rub']['worst'])}",
                 f"±{pct(free_m['hizb']['worst'])}", len(free.mid_phrase)])
    w(table(rows, ["m", "rubʿ CV", "worst rubʿ", "worst hizb", "rubʿ inside a phrase (of 210)"]))
    w(f"\nWith phrase starts only, the limit is phrase granularity: a juz has about 36 phrases, 4.6 per "
      f"rubʿ, and a phrase of 10 long ayat is a fifth of a rubʿ. The default, m = {pct(rub.MID_PHRASE)} with a "
      f"cap of ±{pct(rub.CAP)}, starts {len(d.mid_phrase)} rubʿ inside a phrase "
      f"(traditional: {tr_inside} of the 210 inner rubʿ starts fall inside one of our phrases). Each is "
      "listed in `data/rub/phrase-splits.tsv` as a proposed phrase split for the next review: if the "
      "split is accepted, the rubʿ opens a phrase; if not, re-solve with the phrase kept whole.\n")

    w("## 3. Agreement with the traditional starts\n")
    w(f"{len(same)} of the 240 new rubʿ starts are traditional ones (the 30 juz starts included); "
      f"the median distance between a new start and the traditional start of the same rubʿ is "
      f"{st.median(shifts):g} ayat.\n")

    w("## 4. Worst rubʿ\n")
    w("Traditional (against 1/8 of their juz):\n\n")
    w(table(worst(tmix, trad), ["rubʿ", "juz", "ayat", "combined"]))
    w("\nNew:\n\n")
    w(table(worst(mixv, d.starts), ["rubʿ", "juz", "ayat", "combined"]))

    w("\n## 5. Traditional juz starts inside a phrase\n")
    w(f"The juz are fixed, so where a traditional juz start falls inside a Task 1 phrase, that phrase is "
      f"split there ({len(juz_inside)} cases): {', '.join(juz_inside)}. These are listed with reason `juz` "
      "in `data/rub/phrase-splits.tsv` for the phrase review.\n")

    w("## 6. Takeaways\n")
    w(f"- The traditional juz are within ±6%, but their hizb reach ±{t['hizb']['worst'] * 100:.0f}% and their "
      f"rubʿ ±{t['rub']['worst'] * 100:.0f}% of their share of the juz: the imbalance is in the finer "
      "divisions.\n"
      f"- Keeping the juz and re-cutting inside them brings hizb to ±{n['hizb']['worst'] * 100:.1f}% and rubʿ "
      f"to ±{n['rub']['worst'] * 100:.0f}%, with every hizb opening a subject.\n"
      "- How far rubʿ can be balanced depends on how fine the phrases are; the proposed splits are where "
      "a finer phrase would help most.\n")
    out = ROOT / "docs" / "tasks" / "04-hizb-rub-analysis.md"
    out.write_text("\n".join(o))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
