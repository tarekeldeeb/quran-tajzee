#!/usr/bin/env python3
"""Write the review document of the rubʿ (quarter) split round from its splits.tsv.

    python scripts/review_rub.py [reviews/2026-10-21-rub-splits]

For every quarter boundary that was reviewed it shows each candidate start, its offset, the
text around it, the decision and the reason. Re-run it after editing the decisions.
"""

import statistics as st
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from tajzee import juz as J  # noqa: E402
from tajzee import quran, reviews, rub, scores  # noqa: E402


def main() -> None:
    folder = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "reviews" / "2026-10-21-rub-splits"
    rows = reviews.load_splits(folder / "splits.tsv")
    q = quran.load()
    un = rub.ayat()
    c = rub.mix(un)
    now = rub.solve(un)
    hz = now.hizb_starts() + [len(un)]
    idx = {(u.sura, u.aya): u.index for u in un}
    trad = scores.traditional_starts(1)

    def off_fn(h, k):
        a, b = hz[h - 1], hz[h]
        pre = J._prefix(c[a:b])
        T = pre[-1] / 4
        return lambda i: (pre[i - a] - k * T) / T * 100

    groups = {}
    for r in rows:
        groups.setdefault((int(r["hizb"]), int(r["boundary"])), []).append(r)
    acc = [r for r in rows if r["decision"] == "accept"]
    calls = [r for r in rows if "بديل" in r["why"] or "اجتهاد" in r["why"]]
    rel = rub.relative(un, now.starts, c, 4)
    trel = rub.relative(un, trad, c, 4)
    ab, at = rub.sizes(un, now.starts, c), rub.sizes(un, trad, c)

    o = []
    w = o.append
    w("# Review round 2026-10-21: rubʿ (quarter) splits\n")
    w("*Generated by `scripts/review_rub.py` from `splits.tsv`. Edit the decisions there, not here.*\n")
    if (folder / "STATUS").exists():
        w(f"**Status:** {(folder / 'STATUS').read_text().strip()}\n")

    w("## Result\n")
    w("| | traditional | before this round | after |\n|---|---|---|---|")
    w(f"| quarter CV (against ¼ of its hizb) | {st.pstdev(trel) * 100:.1f}% | 9.2% | **{st.pstdev(rel) * 100:.1f}%** |")
    w(f"| worst quarter | ±{max(map(abs, trel)) * 100:.1f}% | ±23.8% | **±{max(map(abs, rel)) * 100:.1f}%** |")
    w(f"| longest / shortest quarter | {max(at) / min(at):.2f}× | 1.65× | **{max(ab) / min(ab):.2f}×** |")
    w(f"| boundaries inside a phrase | 79 of 210 | 0 | **{len(now.mid_phrase)}** |\n")
    w(f"{len(groups)} quarter boundaries were reviewed, with {len(rows)} candidates read. {len(acc)} splits were "
      f"accepted and {len(groups) - len(acc)} boundaries kept as they were. The hizb approved on 2026-10-21 "
      "are fixed (`data/rub/hizb-approved.tsv`), so no split here moves a hizb. Where the quarters are still "
      "uneven, every closer point is a turn inside a story or a dialogue, and the boundary was kept: "
      "Mūsā at the fire (28:29–35), Hūd (7:65–72), the messengers and their peoples (14:9–12), the "
      "dispute in hell (38:55–64).\n")

    w("## What was done\n")
    w("Each hizb is cut into four quarters, every boundary at a phrase start. For each of its three "
      "inner boundaries:\n\n"
      "1. **Offset.** The boundary's distance from its even position (¼, ½ or ¾ of the hizb), in % of a "
      "quarter, on the 50/50 mix of recitation and print length. −5% means the boundary falls 5% of a "
      "quarter early; the quarter before it is short and the one after it long.\n"
      "2. **Which boundaries.** Those whose current start is more than 3% off. Smaller offsets are not worth "
      "splitting a phrase for.\n"
      "3. **Candidates.** The aya ends inside a phrase that are at least 2 points closer than the current "
      "start: up to the six closest.\n"
      "4. **Reading.** As in the hizb round: a candidate is accepted only at a complete stop, where the aya "
      "before it closes its sentence and subject and the aya after it does not lean on it. Disqualified: a "
      "reply (قال، قالوا), a pointer back (ذلك، أولئك، الذين), a «ف»/«ثم»/«أم»/«إذ» continuation, a "
      "description, a badal, a correlative pair (فإما… وإما، أما… وأما), or a refrain that closes the "
      "verse before it. A change of scene inside a story (a new time or place) is accepted only where "
      "it is marked as a judgment call. The last aya of a surah is not used to open a quarter on its own.\n"
      "5. **Choice.** The closest acceptable candidate is accepted. If none qualifies, the current start "
      "is kept.\n")

    w("## Reading `splits.tsv`\n")
    w("Same columns as the hizb round, plus `hizb` and `boundary` (1, 2 or 3: the start of the 2nd, 3rd or "
      "4th quarter of that hizb). `base_start` is the quarter start before this round and `base_balance` its "
      "offset. `proposed_start` and `proposed_balance` are the candidate and its offset. `inside_phrase` is "
      "the phrase the candidate splits. Rows of the same `hizb` and `boundary` are alternatives for one "
      "boundary. To change a decision, edit `decision` (and the topics for a newly accepted row), then:\n\n"
      "```sh\npython scripts/apply_splits.py --write\nmake scores juz rub paper\npython scripts/review_rub.py\n```\n")

    w("## Judgment calls\n")
    w("Decisions that could reasonably go the other way, either a rejected candidate that could open a "
      "quarter or an accepted one that gives up a surah opening or cuts a scene.\n")
    w("| hizb.boundary | candidate | offset | decision | note |\n|---|---|---|---|---|")
    w("\n".join(f"| {r['hizb']}.{r['boundary']} | {r['proposed_start']} | {r['proposed_balance']} | {r['decision']} "
                f"| {r['why']} |" for r in calls) + "\n")

    w("## Boundary by boundary\n")
    w("¶ marks a phrase start before this round, with its topic; ▶ the quarter start before this round; "
      "★ an accepted new start; ✗ a rejected candidate. The percentage after each aya is the boundary "
      "offset if the quarter started there.\n")
    for (h, k), rs in sorted(groups.items()):
        off = off_fn(h, k)
        base = idx[tuple(map(int, rs[0]["base_start"].split(":")))]
        cand = {idx[tuple(map(int, r["proposed_start"].split(":")))]: r for r in rs}
        new = now.starts[4 * (h - 1) + k]
        lo, hi = min(list(cand) + [base]), max(list(cand) + [base])
        acc_set = {i for i, r in cand.items() if r["decision"] == "accept"}
        while lo > hz[h - 1] and not (un[lo].phrase_start and lo not in acc_set):
            lo -= 1
        w(f"\n### Hizb {h}, quarter {k + 1}: {un[base].ref} ({off(base):+.1f}%) → {un[new].ref} ({off(new):+.1f}%)\n")
        lines = []
        for i in range(lo, hi + 1):
            u = un[i]
            if u.phrase_start and i not in acc_set:
                lines.append(f"¶ *{u.topic}*")
            mark = "▶" if i == base else ("★" if i in acc_set else ("✗" if i in cand else "·"))
            lines.append(f"{mark} **{u.ref}** ({off(i):+.1f}%) {q.ayat[i].text}")
        w("\n" + "  \n".join(lines) + "\n")
        w("\n| candidate | offset | decision | reason |\n|---|---|---|---|")
        w("\n".join(f"| {r['proposed_start']} | {r['proposed_balance']} | "
                    f"{'**accept**' if r['decision'] == 'accept' else 'reject'} | {r['why']} |" for r in rs) + "\n")
        for r in rs:
            if r["decision"] == "accept":
                w(f"\nNew phrases: {r['sura']}:{r['from']}–{r['split_after']} *{r['topic_part1']}* · "
                  f"{r['proposed_start']}–{r['to']} *{r['topic_part2']}*\n")
    out = folder / "README.md"
    out.write_text("\n".join(o))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
