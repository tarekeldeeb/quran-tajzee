#!/usr/bin/env python3
"""Final analysis: the complete division (traditional juz, new hizb and rub').

Writes docs/final-analysis.md. Uses only committed data.
"""

import json
import statistics as st
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from tajzee import DATA, quran, rub, scores  # noqa: E402

W = 0.5


def table(rows, header):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def pct(x, sign=False):
    return f"{x * 100:+.1f}%" if sign else f"{x * 100:.1f}%"


def around_mean(xs):
    m = sum(xs) / len(xs)
    return [x / m - 1 for x in xs]


def summary(xs):
    return dict(cv=st.pstdev(xs), worst=max(abs(x) for x in xs), ratio=(1 + max(xs)) / (1 + min(xs)))


def main() -> None:
    us = rub.ayat()
    c = rub.mix(us, W)
    rec = [u.recitation for u in us]
    px = [u.typeset_px for u in us]
    trad = scores.traditional_starts(1)
    final = rub.solve(us)
    # alternative: the Task 3 optimised juz, with the same nested hizb/rub' inside
    ref_index = {(u.sura, u.aya): u.index for u in us}
    sol3 = json.loads((DATA / "juz" / "solution.json").read_text())
    js3 = [ref_index[tuple(map(int, s.split(":")))] for s in sol3["starts"]]
    alt = rub.solve(us, juz_starts=js3)
    divisions = [("traditional", trad), ("final: traditional juz, new hizb and rubʿ", final.starts),
                 ("alternative: Task 3 juz, new hizb and rubʿ", alt.starts)]

    def levels(starts, values):
        return dict(
            juz=summary(around_mean(rub.sizes(us, starts[::8], values))),
            hizb_abs=summary(around_mean(rub.sizes(us, starts[::4], values))),
            rub_abs=summary(around_mean(rub.sizes(us, starts, values))),
            hizb_rel=summary(rub.relative(us, starts[::4], values, 2)),
            rub_rel=summary(rub.relative(us, starts, values, 4)),
        )

    M = {name: levels(s, c) for name, s in divisions}
    fr_rel = M[divisions[1][0]]["rub_rel"]
    an = json.loads((DATA / "rub" / "analysis.json").read_text())
    tcuts = an["traditional_phrase_cuts"]
    o = []
    w = o.append
    w("# Quran-Tajzee — final analysis\n")
    w("Generated by `scripts/final_analysis.py`; do not edit by hand. Sizes are the 50/50 mix of "
      "recitation (Hafs harakat with madd, Task 2) and print width (DigitalKhatt, Task 2), with the "
      "basmala at surah openings. The phrases are the Task 1 subject phrases, still under review.\n")

    w("## 1. The division\n")
    w("- **Juz:** the traditional 30 of the Madina Mushaf, whose divisions come from al-Ṣafāqusī's "
      "*Ghayth al-Nafʿ* ([study](research/ghayth-al-naf.md)). They are kept: optimising them "
      "(Task 3) moves the worst juz only from ±6% to ±5%.\n"
      "- **Hizb:** new. Each juz is cut in two at the phrase start that best halves it, so every "
      "hizb opens a subject.\n"
      f"- **Rubʿ:** new. Each hizb is cut into four, again only at phrase starts. Every rubʿ is within "
      f"±{fr_rel['worst'] * 100:.0f}% of a quarter of its hizb.\n\n"
      f"**No new boundary cuts into a phrase.** The traditional hizb and rubʿ start inside a subject phrase "
      f"{tcuts['hizb'] + tcuts['rub']} times out of 210 (section 4).\n\n"
      "Every cut is exact: a dynamic program finds the optimum, and the tests check it against "
      "exhaustive search. Data: `data/rub/hizb.tsv`, `data/rub/rub.tsv`.\n")

    w("## 2. Balance at every level\n")
    w("Each unit against its share of its parent (hizb against ½ juz, rubʿ against ¼ hizb):\n\n")
    rows = []
    for name, _ in divisions:
        m = M[name]
        rows.append([name, f"±{pct(m['juz']['worst'])}", f"±{pct(m['hizb_rel']['worst'])}",
                     pct(m["hizb_rel"]["cv"]), f"±{pct(m['rub_rel']['worst'])}", pct(m["rub_rel"]["cv"])])
    w(table(rows, ["division", "worst juz", "worst hizb", "hizb CV", "worst rubʿ", "rubʿ CV"]))
    w("\nEach unit against the mean of its level (all hizb against 1/60, all rubʿ against 1/240). This "
      "includes the juz-to-juz differences:\n\n")
    rows = []
    for name, _ in divisions:
        m = M[name]
        rows.append([name, f"±{pct(m['hizb_abs']['worst'])}", f"{m['hizb_abs']['ratio']:.2f}×",
                     f"±{pct(m['rub_abs']['worst'])}", f"{m['rub_abs']['ratio']:.2f}×"])
    w(table(rows, ["division", "worst hizb", "longest/shortest hizb", "worst rubʿ", "longest/shortest rubʿ"]))
    t, f = M["traditional"], M[divisions[1][0]]
    w(f"\nTraditionally the longest rubʿ is {t['rub_abs']['ratio']:.2f}× the shortest. In the final "
      f"division it is {f['rub_abs']['ratio']:.2f}×, and the longest hizb goes from "
      f"{t['hizb_abs']['ratio']:.2f}× the shortest to {f['hizb_abs']['ratio']:.2f}×. "
      + ("Re-optimising the juz as well would make the hizb more even, but the rubʿ less so, and it "
         "would leave the traditional juz.\n" if M[divisions[2][0]]["rub_abs"]["ratio"] > f["rub_abs"]["ratio"]
         else "Re-optimising the juz as well would gain a little more, at the cost of leaving the "
              "traditional juz.\n"))

    w("## 3. Recitation and print separately\n")
    rows = []
    for label, values in (("recitation", rec), ("print", px), ("mix", c)):
        a, b = levels(trad, values), levels(final.starts, values)
        rows.append([label, f"±{pct(a['hizb_rel']['worst'])} → ±{pct(b['hizb_rel']['worst'])}",
                     f"±{pct(a['rub_rel']['worst'])} → ±{pct(b['rub_rel']['worst'])}",
                     f"{a['rub_abs']['ratio']:.2f}× → {b['rub_abs']['ratio']:.2f}×"])
    w(table(rows, ["score", "worst hizb (½ juz)", "worst rubʿ (¼ hizb)", "longest/shortest rubʿ"]))
    w("\nThe two scores agree closely, so a division that balances the mix balances each one.\n")

    w("## 4. Where the boundaries fall\n")
    jset = set(final.juz_starts)

    def where(starts):
        inner_h = [s for s in starts[::4] if s not in jset]
        inner_r = [s for i, s in enumerate(starts) if i % 4 and s not in jset]
        return dict(
            hizb_phrase=sum(us[s].phrase_start for s in inner_h), hizb_surah=sum(us[s].aya == 1 for s in inner_h),
            rub_phrase=sum(us[s].phrase_start for s in inner_r), rub_surah=sum(us[s].aya == 1 for s in inner_r))

    a, b = where(trad), where(final.starts)
    rows = [["second hizb of a juz (30) opens a phrase", a["hizb_phrase"], b["hizb_phrase"]],
            ["second hizb of a juz (30) opens a surah", a["hizb_surah"], b["hizb_surah"]],
            ["inner rubʿ (180) opens a phrase", a["rub_phrase"], b["rub_phrase"]],
            ["inner rubʿ (180) opens a surah", a["rub_surah"], b["rub_surah"]],
            ["juz (30) opens a phrase", sum(us[s].phrase_start for s in jset), "same"],
            ["juz (30) opens a surah", sum(us[s].aya == 1 for s in jset), "same"]]
    rows.insert(0, ["juz (30) starts inside a phrase", tcuts["juz"], "same (kept)"])
    rows.insert(1, ["second hizb of a juz (30) starts inside a phrase", tcuts["hizb"], 0])
    rows.insert(2, ["inner rubʿ (180) starts inside a phrase", tcuts["rub"], 0])
    w(table(rows, ["boundary", "traditional", "final"]))
    w(f"\nTraditionally {tcuts['juz'] + tcuts['hizb'] + tcuts['rub']} of the 240 rubʿ starts (all levels) "
      "fall inside a subject phrase, typically halfway through it, so the new unit opens in the middle "
      "of a subject. **In the final division no hizb or rubʿ does:** every boundary it adds opens a "
      f"phrase. The {tcuts['juz']} cases left are traditional juz starts, kept as they are. Splitting "
      "those phrases in review makes the whole division phrase-aligned. Every traditional case is "
      "listed in `data/rub/traditional-phrase-cuts.tsv`.\n")
    hs = len(set(final.hizb_starts()) & set(trad[::4])) - 30
    rs = len(set(final.starts) & set(trad)) - len(set(final.hizb_starts()) & set(trad[::4]))
    w(f"\n{hs} of the 30 second-hizb starts and {rs} of the 180 inner rubʿ starts are unchanged. The "
      "final division opens fewer hizb at a surah than the tradition does: the traditional hizb often "
      "start at a surah and accept the imbalance (juz 28: ±13.9%). A surah preference for hizb, like "
      "the juz penalty of Task 3, would trade some of that balance back.\n")

    w("## 5. Juz by juz\n")
    w("Hizb: the start of the second hizb and the larger deviation of the two from ½ juz. "
      "Rubʿ: the worst of the eight against ¼ of their hizb.\n\n")
    js = rub.sizes(us, trad[::8], c)
    jdev = around_mean(js)
    th, fh = rub.relative(us, trad[::4], c, 2), rub.relative(us, final.hizb_starts(), c, 2)
    tr, fr = rub.relative(us, trad, c, 4), rub.relative(us, final.starts, c, 4)
    mids = set(final.mid_phrase)
    rows = []
    for j in range(30):
        s0 = us[trad[8 * j]]
        rows.append([j + 1, f"{s0.ref} {quran.SURAH_NAMES[s0.sura]}", pct(jdev[j], True),
                     us[trad[8 * j + 4]].ref, us[final.starts[8 * j + 4]].ref,
                     f"±{pct(abs(th[2 * j]))}", f"±{pct(abs(fh[2 * j]))}",
                     f"±{pct(max(abs(x) for x in tr[8 * j:8 * j + 8]))}",
                     f"±{pct(max(abs(x) for x in fr[8 * j:8 * j + 8]))}",
                     sum(1 for s in final.starts[8 * j:8 * j + 8] if s in mids)])
    w(table(rows, ["juz", "start", "juz vs mean", "2nd hizb trad.", "2nd hizb new", "hizb trad.",
                   "hizb new", "worst rubʿ trad.", "worst rubʿ new", "rubʿ inside a phrase"]))

    w("\n## 6. Open items\n")
    n_juz = sum(1 for s in jset if not us[s].phrase_start)
    hint = rub.solve(us, objective="penalized")
    hm = rub.relative(us, hint.starts, c, 4)
    w(f"1. **Phrase review, round 2.** `data/rub/phrase-splits.tsv` lists {n_juz + len(hint.mid_phrase)} "
      f"proposed splits. {n_juz} are where a traditional juz starts inside a phrase. "
      f"{len(hint.mid_phrase)} are splits that would let the rubʿ balance better: with all of them "
      f"accepted, the worst rubʿ falls from ±{fr_rel['worst'] * 100:.0f}% to about "
      f"±{max(abs(x) for x in hm) * 100:.0f}%, still with no boundary inside a phrase.\n"
      "2. **Surah preference for hizb** (section 4), if openings matter more than balance at that level.\n"
      "3. **Ghayth al-Nafʿ table.** Al-Ṣafāqusī's 240 boundaries, with the Maghāriba and Mashāriqa "
      "alternatives, as preferred cut points with traditional standing.\n"
      "4. **Agreement across the counting schools** (فاصلة بلا خلاف): checked. Every boundary, traditional "
      "and new, is an aya end in all six counting systems.\n")

    w("## 7. Reproduce\n")
    w("```sh\nmake rub                         # data/rub/*, docs/tasks/04-hizb-rub-analysis.md\n"
      "python scripts/final_analysis.py # this report\n```\n")
    out = ROOT / "docs" / "final-analysis.md"
    out.write_text("\n".join(o))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
