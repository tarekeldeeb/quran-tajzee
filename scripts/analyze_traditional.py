#!/usr/bin/env python3
"""How the traditional rubʿ were drawn, measured: letter counts, stops and phrases.

Writes docs/research/traditional-divisions-analysis.md and data/rub/traditional-rub.tsv.
Uses only committed data.
"""

import bisect
import csv
import statistics as st
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from tajzee import DATA, quran, reviews, rub, scores  # noqa: E402

# first words that make an aya lean on the one before it: a reply, or a fa'/thumma/idh link
LEANING = ("قال", "قالوا", "قالت", "ثم", "إذ", "حتى")


def words(a):
    w = quran.plain(a.text).split()
    return w[4:] if a.aya == 1 and a.sura not in (1, 9) else w


def leans(w):
    return w[0] in LEANING or (w[0].startswith("ف") and not w[0].startswith("فاطر"))


def table(rows, header):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def main() -> None:
    q = quran.load()
    ws = [words(a) for a in q.ayat]
    letters = [sum(len(x) for x in w) for w in ws]
    cum = [0]
    for x in letters:
        cum.append(cum[-1] + x)
    total = cum[-1]
    trad = scores.traditional_starts(1)
    us_read = rub.ayat(reviews.reading())  # phrases as a reading of the text
    us_now = rub.ayat()
    new = rub.solve(us_now).starts

    # 1. distance from equal-letter positions, against what aya ends alone force
    def grid(starts, n, every):
        s = starts[::every]
        unit = total / n
        off, floor = [], []
        for k in range(1, n):
            P = k * unit
            off.append(abs(cum[s[k]] - P) / unit)
            j = bisect.bisect_left(cum, P)
            floor.append(min(abs(cum[x] - P) for x in (j - 1, j)) / unit)
        sizes = [cum[b] - cum[a] for a, b in zip(s, s[1:] + [len(letters)])]
        return st.mean(off), st.mean(floor), max(sizes) / min(sizes)

    def within_juz(starts):
        js = starts[::8] + [len(letters)]
        off, floor, rel = [], [], []
        for j in range(30):
            a, b = js[j], js[j + 1]
            unit = (cum[b] - cum[a]) / 8
            for k in range(8):
                i = starts[8 * j + k]
                e = starts[8 * j + k + 1] if 8 * j + k + 1 < 240 else len(letters)
                rel.append((cum[e] - cum[i]) / unit - 1)
                if k:
                    P = cum[a] + k * unit
                    off.append(abs(cum[i] - P) / unit)
                    jj = bisect.bisect_left(cum, P)
                    floor.append(min(abs(cum[x] - P) for x in (jj - 1, jj)) / unit)
        return st.mean(off), st.mean(floor), rel

    g = {name: grid(trad, n, e) for name, n, e in (("juz", 30, 8), ("hizb", 60, 4), ("rubʿ", 240, 1))}
    w_off, w_floor, w_rel = within_juz(trad)
    n_off, n_floor, n_rel = within_juz(new)

    # 2. stops and phrases at each traditional start
    pstart, plen, cur = {}, {}, 0
    for x in us_read:
        if x.phrase_start:
            cur = x.index
        pstart[x.index] = cur
        plen[cur] = plen.get(cur, 0) + 1
    rows, cuts = [], {"juz": [], "hizb": [], "rubʿ": []}
    lean = {"juz": 0, "hizb": 0, "rubʿ": 0}
    for k, i in enumerate(trad):
        level = "juz" if k % 8 == 0 else ("hizb" if k % 4 == 0 else "rubʿ")
        inside = k > 0 and not us_read[i].phrase_start
        depth = (i - pstart[i]) / plen[pstart[i]] if inside else 0.0
        if inside:
            cuts[level].append(depth)
        if k > 0 and leans(ws[i]):
            lean[level] += 1
        a = q.ayat[i]
        rows.append([k + 1, level, f"{a.sura}:{a.aya}", f"{w_rel[k] * 100:+.1f}", int(inside),
                     round(depth, 2), int(k > 0 and leans(ws[i])), " ".join(ws[i][:5]),
                     " ".join(ws[i - 1][-4:]) if i else "", us_read[pstart[i]].topic])
    with open(DATA / "rub" / "traditional-rub.tsv", "w", encoding="utf-8", newline="") as fh:
        wr = csv.writer(fh, delimiter="\t", lineterminator="\n")
        wr.writerow(["rub", "level", "start", "letters_dev_pct_of_juz_eighth", "inside_phrase", "depth",
                     "leaning_start", "first_words", "previous_aya_ends", "phrase_topic"])
        wr.writerows(rows)
    new_inside = sum(1 for k, i in enumerate(new) if k % 8 and not us_now[i].phrase_start)
    new_lean = sum(1 for k, i in enumerate(new) if k % 8 and leans(ws[i]))
    new_read = sum(1 for k, i in enumerate(new) if k % 8 and not us_read[i].phrase_start)

    o = []
    w = o.append
    w("# The traditional rubʿ, measured\n")
    w("Generated by `scripts/analyze_traditional.py`; do not edit by hand. The method is the one "
      "al-Ṣafāqusī states in *Ghayth al-Nafʿ* (see the [README](../../README.md) and "
      "[the study](ghayth-al-naf.md)). The data are the Madina Mushaf rubʿ starts "
      "(`data/source/hafs-rub-start-ayahs.json`). Letters are the written letters of the Tanzil "
      f"Uthmani text without the basmala: {total:,} in all.\n")

    w("## 1. Drawn at stops, not by count\n")
    w("For each division: how far its starts lie from the equal-letter positions (k/30, k/60 or "
      "k/240 of the letters), in units of that division. The second column is the distance that "
      "aya ends alone force, i.e. the distance to the nearest aya end.\n\n")
    rr = [[name, f"{o_ * 100:.1f}%", f"{f_ * 100:.2f}%", f"{o_ / f_:.0f}×", f"{r_:.2f}×"]
          for name, (o_, f_, r_) in g.items()]
    rr.append(["rubʿ, inside its own juz", f"{w_off * 100:.1f}%", f"{w_floor * 100:.2f}%",
               f"{w_off / w_floor:.0f}×", "–"])
    w(table(rr, ["division", "mean distance from equal position", "forced by aya ends",
                 "excess", "longest/shortest (letters)"]))
    w(f"\nThe juz lie close to equal-letter positions: {g['juz'][0] * 100:.1f}% of a juz on "
      f"average. Inside a juz, the rubʿ lie {w_off * 100:.0f}% of a rubʿ from equal positions, "
      f"{w_off / w_floor:.0f} times further than aya ends would force. Their lengths vary by "
      f"{g['rubʿ'][2]:.1f}× in letters. This is what al-Ṣafāqusī describes: he does not compute "
      "the quarters. He takes the agreed or well-known ones and ends each at a proper stop. "
      "The quarters were drawn where a thought ends, not by count.\n")

    w("## 2. But many quarters do not start where a thought starts\n")
    w("The stated rule is that every quarter ends at a complete stop (*waqf tāmm*): what follows "
      "does not depend on it, in wording or in meaning. Two checks show where the transmitted "
      "boundaries break that rule. The first is against our reading of the text, the second against "
      "the wording alone:\n\n"
      "- **Inside a phrase.** The start falls inside one of the Task 1 subject phrases. Those "
      "are the phrases as a reading of the text, with the splits made to fit divisions merged back. "
      "The aya before the boundary and the aya after it belong to one subject.\n"
      "- **Leaning start.** The first word ties the aya to the one before it: a reply "
      "(«قال»، «قالوا»، «قالت»), or «ف»، «ثم»، «إذ»، «حتى». Such a start continues a "
      "sentence, a story or a dialogue. The check is crude: a resumptive «ف» (as in «فاصدع بما "
      "تؤمر») opens a new subject, so a flag is a prompt to read the text, not a verdict.\n\n")
    tot = {"juz": 29, "hizb": 30, "rubʿ": 180}
    rr = []
    for lv in ("juz", "hizb", "rubʿ"):
        v = cuts[lv]
        rr.append([{"juz": "juz starts (29)", "hizb": "second-hizb starts (30)", "rubʿ": "other rubʿ starts (180)"}[lv],
                   f"{len(v)} ({len(v) / tot[lv] * 100:.0f}%)", f"{st.median(v) * 100:.0f}%" if v else "–", lean[lv]])
    allc = sum(cuts.values(), [])
    rr.append(["all 239", f"{len(allc)} ({len(allc) / 239 * 100:.0f}%)", f"{st.median(allc) * 100:.0f}%",
               sum(lean.values())])
    w(table(rr, ["boundary", "inside a phrase", "median depth into the phrase", "leaning start"]))
    w(f"\n**{len(allc)} of the 239 traditional starts fall inside a subject phrase**, typically "
      f"halfway through it, and {sum(lean.values())} open with a word that leans on the aya "
      "before. Examples:\n\n")
    ex = [("16", "18:75", "قال ألم أقل لك إنك لن تستطيع معي صبرا",
           "juz 16 opens in the middle of the dialogue of Mūsā and al-Khaḍir, at al-Khaḍir's second reproach"),
          ("27", "51:31", "قال فما خطبكم أيها المرسلون",
           "juz 27 opens with Ibrāhīm's question to the guests whose story began in 51:24"),
          ("23", "37:145", "فنبذناه بالعراء وهو سقيم",
           "the second hizb of juz 23 opens in the middle of the story of Yūnus"),
          ("9", "7:88", "قال الملأ الذين استكبروا من قومه",
           "juz 9 opens with the chiefs' answer to Shuʿayb"),
          ("20", "27:56", "فما كان جواب قومه إلا أن قالوا",
           "juz 20 opens with the answer of Lūṭ's people to his question in 27:55"),
          ("13", "12:77", "قالوا إن يسرق فقد سرق أخ له من قبل",
           "a rubʿ opens with the brothers' reply, in the middle of the scene at the cup"),
          ("16", "19:22", "فحملته فانتبذت به مكانا قصيا",
           "a rubʿ opens in the middle of the story of Maryam"),
          ("19", "26:111", "قالوا أنؤمن لك واتبعك الأرذلون",
           "a rubʿ opens with the reply of Nūḥ's people")]
    w(table([[e[1], f"«{e[2]}»", e[3]] for e in ex], ["start", "opens with", "what it cuts"]))
    w("\nEvery traditional start, with its measures, is in `data/rub/traditional-rub.tsv`.\n")

    w("## 3. The issue\n")
    w("The rule is right. Al-Ṣafāqusī ends each quarter at a proper stop, so that the unit "
      "is complete in meaning. The transmitted quarters follow it only partly:\n\n"
      f"1. **Uneven.** The quarters are not computed, so their lengths vary by {g['rubʿ'][2]:.1f}× in "
      "letters and by about 2.2× on recitation and print. A reader's daily portion or a "
      "printer's page budget changes with them.\n"
      f"2. **Not at the ends of thoughts after all.** {len(allc)} of 239 boundaries fall inside a "
      f"subject phrase, and {sum(lean.values())} open with a reply or a connective. The chosen "
      "boundaries do not keep the rule they were chosen by.\n\n"
      "Quran-Tajzee applies the same rule to every boundary: a quarter ends at the end of a thought, "
      "here the end of a subject phrase. It then chooses among the stops that satisfy the rule by "
      "measured length:\n\n")
    w(table([["mean distance of a rubʿ start from equal position (within its juz)", f"{w_off * 100:.0f}%",
              f"{n_off * 100:.0f}%"],
             ["rubʿ starts inside a subject phrase (of 210 inside the juz)",
              str(len(cuts["hizb"]) + len(cuts["rubʿ"])),
              f"{new_inside}; {new_read} at reviewed complete stops added in round 2026-10-18"],
             ["rubʿ starts with a leaning first word (of 210)", str(lean["hizb"] + lean["rubʿ"]), str(new_lean)]],
            ["measure", "traditional", "Quran-Tajzee"]))
    w("\n**How to read this table.** The phrase test cannot judge the new division: its boundaries are "
      "phrase starts by construction, and the phrases are one reading of the text, still under "
      "review. The wording test is independent of that reading, and on it the two divisions score "
      "alike. Most new flags are a resumptive «ف» at a new subject, such as «فاصدع» (15:94), «فلا "
      "تطع» (68:8) and «فإذا جاءت الطامة» (79:34). A few are real: 11:91, 12:77, 26:116 and 27:27 open "
      "on a reply inside a dialogue, because a 10-aya phrase limit splits long stories at turns of "
      "the dialogue. Two things would settle the meaning question independently. One is the pause "
      "grades of a classical *waqf* work (al-Dānī's *al-Muktafā*, al-Ushmūnī's *Manār al-Hudā*) at "
      "every candidate aya end. The other is a review of the new starts that open on a reply.\n")
    w("\nSee the [final analysis](../final-analysis.md) for the balance of the new division.\n")
    out = ROOT / "docs" / "research" / "traditional-divisions-analysis.md"
    out.write_text("\n".join(o))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
